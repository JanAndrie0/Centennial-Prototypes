// Regenerates assets/js/icons.js from the Heroicons SVGs in assets/icons/outline/.
// Run after adding an icon:  node tools/build-icons.js
// (Maintenance helper only; pages never need a build step.)
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const srcDir = path.join(root, 'assets', 'icons', 'outline');
const outFile = path.join(root, 'assets', 'js', 'icons.js');

const paths = {};
for (const file of fs.readdirSync(srcDir).filter(f => f.endsWith('.svg')).sort()) {
  const svg = fs.readFileSync(path.join(srcDir, file), 'utf8');
  paths[file.replace(/\.svg$/, '')] = [...svg.matchAll(/\sd="([^"]+)"/g)].map(m => m[1]);
}

const out = `/* Heroicons v2.2.0, outline 24px (MIT, Tailwind Labs). Generated by tools/build-icons.js
   from assets/icons/outline/*.svg; edit the SVGs and re-run, don't edit this file by hand. */
(function (CNS) {
  'use strict';

  var PATHS = ${JSON.stringify(paths, null, 2).replace(/\n/g, '\n  ')};

  // Returns inline SVG markup. Icons are decorative: the text label next to them carries the meaning.
  CNS.icon = function (name, className) {
    var d = PATHS[name];
    if (!d) throw new Error('Unknown icon: ' + name);
    return '<svg class="icon' + (className ? ' ' + className : '') + '" viewBox="0 0 24 24" fill="none" ' +
      'stroke="currentColor" stroke-width="1.5" aria-hidden="true" focusable="false">' +
      d.map(function (p) { return '<path stroke-linecap="round" stroke-linejoin="round" d="' + p + '"/>'; }).join('') +
      '</svg>';
  };
})(window.CNS);
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, out);
console.log('Wrote ' + path.relative(root, outFile) + ' with ' + Object.keys(paths).length + ' icons');
